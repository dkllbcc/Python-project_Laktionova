# даны два числа. вывести в начале большее, затем меньшее из них.

# объяснение: если первое число больше второго выводиться сначала первое,а потом второе. в любом дугом случае наоборот

x = int(input("Введите первое число: "))
y = int(input("Введите второе число: "))

if x > y:
    print(x, y)
else:
    print(y, x)


